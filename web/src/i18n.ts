// UI translations (English / Thai). No dependencies; safe to import from node (unit tests): every browser API is guarded.
// Server error messages stay English. User data (group/member/bill names) is never translated.

export type Lang = "en" | "th";
const KEY = "share.lang";

let current: Lang | null = null;

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "th") return saved;
  } catch {
    /* storage unavailable: fall through to browser language */
  }
  try {
    if (typeof navigator !== "undefined" && /^th\b/i.test(navigator.language ?? "")) return "th";
  } catch {
    /* ignore */
  }
  return "en";
}

function applyDocumentLang(l: Lang) {
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

export function lang(): Lang {
  if (!current) {
    current = detect();
    applyDocumentLang(current);
  }
  return current;
}

export function setLang(l: Lang) {
  current = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* storage unavailable: choice lasts for this page only */
  }
  applyDocumentLang(l);
}

/** Locale for Intl / toLocale*String. `undefined` = browser default (English UI). */
export const locale = () => (lang() === "th" ? "th-TH" : undefined);

export type TKey = keyof typeof en;
type Params = Record<string, string | number>;
type PluralBase = { [K in TKey]: K extends `${infer B}.one` ? B : never }[TKey];

function fill(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

export function t(key: TKey, params?: Params): string {
  const dict: Record<TKey, string> = lang() === "th" ? th : en;
  return fill(dict[key] ?? en[key], params);
}

/** Plural helper: picks `<base>.one` when n === 1, else `<base>.other`; `{n}` is always available. */
export function tn(base: PluralBase, n: number, params?: Params): string {
  const key = `${base}.${n === 1 ? "one" : "other"}` as TKey;
  return t(key, { n, ...params });
}

